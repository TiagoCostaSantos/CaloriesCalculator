package com.CaloriesCalculator.model;

public class MacroNutrientesModel {

    private Double carboidratos;
    private Double proteinas;
    private Double gordurasGerais;

    public Double getCarboidratos() {
        return carboidratos;
    }

    public void setCarboidratos(Double carboidratos) {
        this.carboidratos = carboidratos;
    }

    public Double getProteinas() {
        return proteinas;
    }

    public void setProteinas(Double proteinas) {
        this.proteinas = proteinas;
    }

    public Double getGordurasGerais() {
        return gordurasGerais;
    }

    public void setGordurasGerais(Double gordurasGerais) {
        this.gordurasGerais = gordurasGerais;
    }
}
